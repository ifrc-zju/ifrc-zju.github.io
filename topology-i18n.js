  function detectTopologyLang() {
    var q = global.location.search || '';
    var m = q.match(/[?&]lang=(zh|zhtw|en|ja|ko|th)(?:&|$)/);
    return m ? m[1] : 'zh';
  }

  function htmlLangAttr(lang) {
    if (lang === 'zh') return 'zh-CN';
    if (lang === 'zhtw') return 'zh-TW';
    if (lang === 'ja') return 'ja';
    if (lang === 'ko') return 'ko';
    if (lang === 'th') return 'th';
    return 'en';
  }

  function applyTopologyI18n() {
    var lang = detectTopologyLang();
    global.document.documentElement.setAttribute('lang', htmlLangAttr(lang));

    if (lang === 'zh') {
      var h = global.document.querySelector('header h1');
      if (h && !global.document.body.classList.contains('topology-embed')) {
        global.document.title = h.textContent.replace(/\s+/g, ' ').trim();
      }
      return;
    }

    var pack = PACK[lang] || {};
    var en = PACK.en || {};
    function t(k) {
      return pack[k] || en[k] || '';
    }

    var pt = t('pageTitle');
    if (pt) global.document.title = pt;

    global.document.querySelectorAll('[data-i18n]').forEach(function (el) {
      var k = el.getAttribute('data-i18n');
      if (!k) return;
      var s = t(k);
      if (s) el.textContent = s;
    });

    var svg = global.document.querySelector('svg.graph-svg');
    if (svg) {
      var aria = t('svgAria');
      if (aria) svg.setAttribute('aria-label', aria);
    }
  }

